#!/usr/bin/env python3
"""
Fetch auction house prices for other WoW Classic realms from the Blizzard Game Data API
and write them to ../ExternalData.lua so AHelper can show cross-realm investments.

Addons cannot reach the internet, so run this on your PC (e.g. before playing), then /reload in game.

Setup (one time):
  1. Create a free API client at https://develop.battle.net/access/clients  (any redirect URL)
  2. Set environment variables BLIZZARD_CLIENT_ID and BLIZZARD_CLIENT_SECRET
     (or pass --client-id / --client-secret, or put them in tools/config.json)

Usage:
  python fetch_prices.py --list-realms
  python fetch_prices.py --realms whitemane,nightslayer --factions alliance,horde

Namespaces: Classic Era / Anniversary realms live in "dynamic-classic1x-<region>",
progression Classic in "dynamic-classic-<region>". Use --namespace to override if Blizzard changes it.
Only Python standard library is used.
"""
import argparse
import base64
import json
import os
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, "..", "ExternalData.lua")
MARKET_FRACTION = 0.15  # same definition as the addon: avg of cheapest 15% of listed quantity


def load_config():
    path = os.path.join(HERE, "config.json")
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    return {}


def http_json(url, token=None, data=None, basic=None, retries=3):
    headers = {"User-Agent": "AHelper-price-fetcher"}
    if token:
        headers["Authorization"] = "Bearer " + token
    if basic:
        headers["Authorization"] = "Basic " + base64.b64encode(basic.encode()).decode()
    body = urllib.parse.urlencode(data).encode() if data else None
    for attempt in range(retries):
        try:
            req = urllib.request.Request(url, data=body, headers=headers)
            with urllib.request.urlopen(req, timeout=60) as resp:
                return json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as e:
            if e.code == 429 or e.code >= 500:
                time.sleep(2 ** attempt)
                continue
            raise
        except urllib.error.URLError:
            time.sleep(2 ** attempt)
    raise RuntimeError("request failed: " + url)


class Api:
    def __init__(self, client_id, secret, region, namespace, locale):
        self.region = region
        self.namespace = namespace
        self.locale = locale
        tok = http_json("https://oauth.battle.net/token", data={"grant_type": "client_credentials"},
                        basic=f"{client_id}:{secret}")
        self.token = tok["access_token"]

    def get(self, path, **params):
        params.setdefault("namespace", self.namespace)
        params.setdefault("locale", self.locale)
        url = f"https://{self.region}.api.blizzard.com{path}?" + urllib.parse.urlencode(params)
        return http_json(url, token=self.token)

    def get_href(self, href):
        sep = "&" if "?" in href else "?"
        return http_json(href + sep + urllib.parse.urlencode({"locale": self.locale}), token=self.token)


def market_stats(listings):
    """listings: list of (unit_price, quantity). Returns (market, min, total_qty)."""
    listings.sort(key=lambda x: x[0])
    total = sum(q for _, q in listings)
    want = max(1, round(total * MARKET_FRACTION))
    got = 0
    acc = 0.0
    for unit, q in listings:
        take = min(q, want - got)
        acc += unit * take
        got += take
        if got >= want:
            break
    return int(acc / got), int(listings[0][0]), total


def faction_of(ah_name, ah_id):
    n = (ah_name or "").lower()
    if "alliance" in n or ah_id == 2:
        return "Alliance"
    if "horde" in n or ah_id == 6:
        return "Horde"
    return "Neutral"


def lua_file(realms, generated):
    out = ["-- AHelper: external price data. GENERATED by tools/fetch_prices.py - do not edit.",
           f"-- Generated {time.strftime('%Y-%m-%d %H:%M:%S', time.localtime(generated))}",
           "AHelper_External = {", f"  generated = {generated},", "  realms = {"]
    for key in sorted(realms):
        out.append(f'    ["{key}"] = {{')
        items = realms[key]
        for item_id in sorted(items):
            m, mn, q = items[item_id]
            out.append(f"      [{item_id}]={{{m},{mn},{q}}},")
        out.append("    },")
    out += ["  },", "}", ""]
    return "\n".join(out)


def main():
    cfg = load_config()
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--client-id", default=os.environ.get("BLIZZARD_CLIENT_ID", cfg.get("client_id")))
    p.add_argument("--client-secret", default=os.environ.get("BLIZZARD_CLIENT_SECRET", cfg.get("client_secret")))
    p.add_argument("--region", default=cfg.get("region", "us"), choices=["us", "eu", "kr", "tw"])
    p.add_argument("--namespace", default=cfg.get("namespace"),
                   help="default: dynamic-classic1x-<region> (Classic Era / Anniversary)")
    p.add_argument("--locale", default=cfg.get("locale", "en_US"))
    p.add_argument("--realms", default=",".join(cfg.get("realms", [])),
                   help="comma separated realm slugs (see --list-realms)")
    p.add_argument("--factions", default=",".join(cfg.get("factions", ["alliance", "horde"])),
                   help="alliance,horde,neutral")
    p.add_argument("--min-qty", type=int, default=cfg.get("min_qty", 1),
                   help="skip items with fewer units listed than this")
    p.add_argument("--out", default=DEFAULT_OUT)
    p.add_argument("--list-realms", action="store_true")
    a = p.parse_args()

    if not a.client_id or not a.client_secret:
        sys.exit("Missing API credentials: set BLIZZARD_CLIENT_ID / BLIZZARD_CLIENT_SECRET (see --help).")
    ns = a.namespace or f"dynamic-classic1x-{a.region}"
    api = Api(a.client_id, a.client_secret, a.region, ns, a.locale)

    if a.list_realms:
        idx = api.get("/data/wow/realm/index")
        for r in sorted(idx.get("realms", []), key=lambda r: r["slug"]):
            print(f"{r['slug']:30s} {r['name']}")
        return

    slugs = [s.strip() for s in a.realms.split(",") if s.strip()]
    if not slugs:
        sys.exit("No realms given. Use --realms slug1,slug2 (find slugs with --list-realms).")
    want_factions = {f.strip().capitalize() for f in a.factions.split(",") if f.strip()}

    result = {}
    done_connected = set()
    for slug in slugs:
        try:
            realm = api.get(f"/data/wow/realm/{slug}")
        except urllib.error.HTTPError as e:
            print(f"! realm '{slug}' not found in namespace {ns} ({e.code})")
            continue
        name = realm["name"]
        cr_href = realm["connected_realm"]["href"]
        cr_id = int(cr_href.split("/connected-realm/")[1].split("?")[0])
        if cr_id in done_connected:
            continue
        done_connected.add(cr_id)
        houses = api.get(f"/data/wow/connected-realm/{cr_id}/auctions/index").get("auctions", [])
        for house in houses:
            ah_id = house.get("id")
            faction = faction_of(house.get("name"), ah_id)
            if faction not in want_factions:
                continue
            data = api.get(f"/data/wow/connected-realm/{cr_id}/auctions/{ah_id}")
            per_item = {}
            for au in data.get("auctions", []):
                buyout = au.get("buyout") or 0
                qty = au.get("quantity") or 1
                if buyout <= 0:
                    continue
                item_id = au["item"]["id"]
                per_item.setdefault(item_id, []).append((buyout / qty, qty))
            items = {}
            for item_id, listings in per_item.items():
                m, mn, q = market_stats(listings)
                if q >= a.min_qty:
                    items[item_id] = (m, mn, q)
            key = f"{name}-{faction}"
            result[key] = items
            print(f"  {key}: {len(data.get('auctions', []))} auctions, {len(items)} items")

    if not result:
        sys.exit("No data fetched. Check realm slugs / namespace.")
    generated = int(time.time())
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(lua_file(result, generated))
    print(f"wrote {os.path.abspath(a.out)} - /reload in game to use it")


if __name__ == "__main__":
    main()
